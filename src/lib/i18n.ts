// Dynamic Database translations helper
export function getLocalized<T extends { translations?: any[] }>(
  item: T,
  field: string,
  currentLang: string,
  fallbackValue: string = ''
): string {
  if (!item) return fallbackValue;
  
  // If the language is English, return the default field on the model
  if (currentLang === 'en') {
    return (item as any)[field] || fallbackValue;
  }

  // Look for translations array
  if (item.translations && Array.isArray(item.translations)) {
    const matched = item.translations.find(
      (t) => t.languageCode === currentLang
    );
    if (matched && matched[field] !== undefined && matched[field] !== null && matched[field] !== '') {
      return matched[field];
    }
  }

  // Fallback to English field on main model
  return (item as any)[field] || fallbackValue;
}
